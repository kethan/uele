/**
 * Pre-computes gzip sizes for every code example so the docs can show a
 * "~X KB gzip" badge next to each example — emphasizing uele's minimal,
 * byte-friendly footprint.
 *
 * uele itself (and all uele/* subpaths) are treated as external — they are
 * already loaded on the page as vendor bundles — so the measured size is the
 * *marginal* cost of just the example code, bundled + treeshaken + gzipped.
 *
 * Reads src/content/examples.js + src/content/home.js (HERO_CODE),
 * bundles each with esbuild (JSX transform + treeshaking, uele external),
 * gzips the bundle output, and writes src/example-sizes.js.
 *
 * Every fenced code block ( ```jsx ) on every docs page gets a size badge.
 * Regenerated by dev/build (added to postinstall).
 */
import { gzipSync } from "node:zlib";
import { writeFileSync, mkdirSync, mkdtempSync, rmSync, existsSync, readFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build } from "esbuild";
import { tmpdir } from "node:os";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");

// On Windows, import() requires a file:// URL, not a raw C:\... path.
const importLocal = (p) => import(pathToFileURL(resolve(p)).href);

const { EXAMPLES } = await importLocal(root + "/src/content/examples.js");
const { HERO_CODE } = await importLocal(root + "/src/content/home.js");
const { PAGES } = await importLocal(root + "/src/content/pages/index.js");

const tmpDir = mkdtempSync(resolve(tmpdir(), "uele-sizes-"));

// JSX runtime module that provides jsx/jsxs/Fragment exports backed by uele's h().
// uele is external so this stays tiny.
const JSX_RUNTIME_SOURCE = `
import { h } from "uele";
export const jsx = (tag, props = {}, ...children) => h(tag, props, ...children);
export const jsxs = jsx;
export const Fragment = Symbol("fragment");
export const jsxDEV = jsx;
`;

// All uele subpaths are external — already loaded on the page as vendor bundles.
// Only npm packages (ulive, udomdiff, @preact/signals-core) get bundled inline.
const uelePlugin = {
  name: "uele",
  setup(build) {
    // Mark all uele/* specifiers as external
    build.onResolve({ filter: /^uele(\/.*)?$/ }, () => ({ external: true }));

    // Virtual JSX runtime backed by external `uele`
    build.onLoad({ filter: /^uele-jsx-runtime-virtual$/ }, () => ({
      contents: JSX_RUNTIME_SOURCE,
      loader: "js",
    }));

    // Resolve bare npm packages from website/node_modules
    build.onResolve({ filter: /^[^.]/ }, (args) => {
      const candidate = resolve(root, "node_modules", args.path);
      if (existsSync(candidate)) {
        try {
          const pkgPath = resolve(candidate, "package.json");
          if (existsSync(pkgPath)) {
            const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
            const entry =
              pkg.exports?.["."]?.import ||
              pkg.module ||
              pkg.main;
            if (entry) {
              return { path: resolve(candidate, entry), namespace: "file" };
            }
          }
        } catch {
          /* fall through */
        }
        return { path: candidate, namespace: "file" };
      }
      return undefined;
    });
  },
};

const bundleSize = async (code, entryName) => {
  const entryFile = resolve(tmpDir, entryName);
  writeFileSync(entryFile, code);
  try {
    const result = await build({
      entryPoints: [entryFile],
      bundle: true,
      format: "esm",
      platform: "browser",
      target: ["es2020"],
      legalComments: "none",
      logLevel: "silent",
      write: false,
      loader: { ".js": "jsx" },
      jsx: "automatic",
      jsxImportSource: "uele",
      absWorkingDir: root,
      plugins: [uelePlugin],
    });
    const output = result.outputFiles[0];
    return gzipSync(output.contents).length;
  } finally {
    rmSync(entryFile, { force: true });
  }
};

const sizes = {};

for (const ex of EXAMPLES) {
  sizes[ex.id] = await bundleSize(ex.code, `ex-${ex.id}.js`);
}
sizes.hero = await bundleSize(HERO_CODE, "hero.js");

// Size every fenced code block on every docs page (not just live fences).
// All pages with examples get size badges.
// Only size fences where the opening ``` is at the start of a line.
for (const [slug, page] of Object.entries(PAGES)) {
  const fenceRegex = /^```([^\n]*)\n([\s\S]*?)\n```/gm;
  let match;
  let i = 0;
  while ((match = fenceRegex.exec(page.markdown)) !== null) {
    const lang = match[1].trim() || "jsx";
    // Only size JSX/JS fences — skip bash, json, css, etc.
    if (lang === "jsx" || lang === "js" || lang === "") {
      try {
        sizes[`${slug}:fence${i}`] = await bundleSize(match[2], `${slug}-fence${i}.js`);
      } catch {
        // Skip fences that aren't valid JavaScript (e.g. markdown text in backticks)
      }
    }
    i++;
  }
}

rmSync(tmpDir, { recursive: true, force: true });

const outDir = resolve(root, "src");
mkdirSync(outDir, { recursive: true });
const sizesJs =
  "// Auto-generated by scripts/example-sizes.mjs — do not edit.\n" +
  "export const EXAMPLE_SIZES = " +
  JSON.stringify(sizes, null, 2) +
  ";\n" +
  "export const formatSize = (bytes) => {\n" +
  '  if (bytes < 1024) return `~${bytes} B gzip`;\n' +
  '  const kb = bytes / 1024;\n' +
  '  return kb < 1024 ? `~${Math.round(kb)} KB gzip` : `~${(kb / 1024).toFixed(1)} MB gzip`;\n' +
  "};\n";
writeFileSync(resolve(outDir, "example-sizes.js"), sizesJs);
console.log(`[example-sizes] wrote ${Object.keys(sizes).length} sizes to src/example-sizes.js`);
